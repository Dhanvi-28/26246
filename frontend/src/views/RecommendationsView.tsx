import React, { useState, useEffect } from 'react';
import {
  CheckCircle2,
  Sliders,
  AlertCircle,
  FileText,
  Clock,
  ArrowRight,
  Shield,
  Layers
} from 'lucide-react';
import { RecommendationItem } from '../types/api';
import { fetchRecommendations, updateRecommendationStatus } from '../lib/api';

interface RecommendationsViewProps {
  filterParams: Record<string, string>;
  onNavigateToScenario?: (trade: string) => void;
}

export const RecommendationsView: React.FC<RecommendationsViewProps> = ({
  filterParams,
  onNavigateToScenario,
}) => {
  const [recommendations, setRecommendations] = useState<RecommendationItem[]>([]);
  const [loading, setLoading] = useState(true);
  const [statusFilter, setStatusFilter] = useState('');
  const [updatingId, setUpdatingId] = useState<number | null>(null);

  const loadRecommendations = () => {
    setLoading(true);
    const params: Record<string, string> = { ...filterParams };
    if (statusFilter) params.status = statusFilter;

    fetchRecommendations(params)
      .then((res) => {
        setRecommendations(res);
        setLoading(false);
      })
      .catch((err) => {
        console.error(err);
        setLoading(false);
      });
  };

  useEffect(() => {
    loadRecommendations();
  }, [JSON.stringify(filterParams), statusFilter]);

  const handleStatusChange = async (recId: number, newStatus: string) => {
    setUpdatingId(recId);
    try {
      await updateRecommendationStatus(recId, newStatus);
      setRecommendations((prev) =>
        prev.map((r) => (r.id === recId ? { ...r, status: newStatus } : r))
      );
    } catch (e) {
      console.error(e);
    } finally {
      setUpdatingId(null);
    }
  };

  if (loading) {
    return (
      <div className="space-y-4 animate-pulse">
        {[...Array(3)].map((_, i) => (
          <div key={i} className="h-44 rounded-xl bg-navy-900 border border-navy-800" />
        ))}
      </div>
    );
  }

  return (
    <div className="space-y-6">
      {/* Header Banner */}
      <div className="flex flex-wrap items-center justify-between gap-4 p-5 rounded-xl bg-gradient-to-r from-navy-900 via-navy-850 to-navy-900 border border-gold-500/30 shadow-navy-card">
        <div>
          <h3 className="text-base font-bold text-white flex items-center gap-2">
            <CheckCircle2 className="w-5 h-5 text-gold-400" />
            Decision-Support Intervention Recommendations
          </h3>
          <p className="text-xs text-slate-300 mt-1 max-w-2xl leading-relaxed">
            Deterministic, explainable policy actions generated by matching forecasted headcount deficits against historical institutional absorption rates.
          </p>
        </div>

        <div className="flex items-center gap-2">
          <span className="text-xs text-slate-400">Action Status:</span>
          <select
            value={statusFilter}
            onChange={(e) => setStatusFilter(e.target.value)}
            className="bg-navy-950 border border-navy-700 rounded-lg px-2.5 py-1 text-xs text-white focus:outline-none focus:border-gold-500"
          >
            <option value="">All Recommendations</option>
            <option value="proposed">Proposed</option>
            <option value="under_review">Under Review</option>
            <option value="accepted">Accepted</option>
            <option value="rejected">Rejected</option>
            <option value="completed">Completed</option>
          </select>
        </div>
      </div>

      {/* Recommendations Cards */}
      {recommendations.length === 0 ? (
        <div className="p-12 text-center rounded-xl bg-navy-900 border border-navy-800 text-slate-400">
          No recommendations found for the selected filter scope.
        </div>
      ) : (
        <div className="space-y-4">
          {recommendations.map((rec) => {
            const isAccepted = rec.status === 'accepted';
            const isRejected = rec.status === 'rejected';

            return (
              <div
                key={rec.id}
                className={`p-5 rounded-xl border transition-all ${
                  isAccepted
                    ? 'bg-navy-900/90 border-emerald-500/40 shadow-sm'
                    : isRejected
                    ? 'bg-navy-900/50 border-navy-800 opacity-60'
                    : 'bg-navy-900/90 border-navy-700/60 hover:border-gold-500/30 shadow-navy-card'
                }`}
              >
                <div className="flex flex-wrap items-start justify-between gap-3">
                  <div className="space-y-1.5 max-w-3xl">
                    <div className="flex flex-wrap items-center gap-2">
                      <span className="px-2 py-0.5 rounded text-[10px] font-bold uppercase tracking-wider bg-gold-500/10 text-gold-300 border border-gold-500/30">
                        {rec.action_type.replace('_', ' ')}
                      </span>
                      <span className="text-xs text-slate-400 font-medium">
                        {rec.district_name}, {rec.state_name} • {rec.sector_name}
                      </span>
                      <span className="text-[10px] px-1.5 py-0.5 rounded bg-navy-800 text-slate-400 border border-navy-700">
                        Confidence: {rec.confidence}
                      </span>
                    </div>

                    <h4 className="text-sm font-bold text-white pt-1">{rec.title}</h4>

                    <p className="text-xs text-slate-200 leading-relaxed font-medium">
                      <strong>Proposed Action:</strong> {rec.proposed_action}
                    </p>

                    <p className="text-xs text-slate-400 leading-relaxed">
                      <strong>Rationale:</strong> {rec.reasoning}
                    </p>

                    {rec.caveats && (
                      <div className="flex items-start gap-1.5 p-2 rounded-lg bg-navy-950 border border-navy-800 text-[11px] text-amber-300/90">
                        <AlertCircle className="w-3.5 h-3.5 shrink-0 mt-0.5 text-amber-400" />
                        <span>Caveat / Precondition: {rec.caveats}</span>
                      </div>
                    )}
                  </div>

                  {/* Status & Review Period Dropdown */}
                  <div className="flex flex-col sm:items-end gap-3 shrink-0">
                    <div className="flex items-center gap-1.5 text-xs text-slate-400">
                      <Clock className="w-3.5 h-3.5 text-gold-400" />
                      <span>Review by: {rec.suggested_review_period}</span>
                    </div>

                    <div className="flex items-center gap-2">
                      <span className="text-xs text-slate-400">Status:</span>
                      <select
                        value={rec.status}
                        onChange={(e) => handleStatusChange(rec.id, e.target.value)}
                        disabled={updatingId === rec.id}
                        className={`px-2.5 py-1 rounded text-xs font-semibold border focus:outline-none transition-colors ${
                          rec.status === 'accepted'
                            ? 'bg-emerald-950 text-emerald-300 border-emerald-500/40'
                            : rec.status === 'under_review'
                            ? 'bg-amber-950 text-amber-300 border-amber-500/40'
                            : rec.status === 'rejected'
                            ? 'bg-rose-950 text-rose-300 border-rose-500/40'
                            : 'bg-navy-950 text-slate-300 border-navy-700'
                        }`}
                      >
                        <option value="proposed">Proposed</option>
                        <option value="under_review">Under Review</option>
                        <option value="accepted">Accepted</option>
                        <option value="rejected">Rejected</option>
                        <option value="completed">Completed</option>
                      </select>
                    </div>
                  </div>
                </div>
              </div>
            );
          })}
        </div>
      )}
    </div>
  );
};
